  out << "      if (out_dist2) out_dist2[i] = neighbors[i].dist2;\n";
  out << "    }\n";
  out << "    if (out_count) *out_count = count;\n";
  out << "    return count > 0;\n";
  out << "  } catch (...) {\n";
  out << "    return false;\n";
  out << "  }\n";
  out << "}\n";
  out << "\n";
  out << "bool " << prefix << "_infer_ann_query(\n";
