  out << "      return false;\n";
  out << "    }\n";
  out << "    uint32_t count = static_cast<uint32_t>(neighbors.size());\n";
  out << "    if (count > capacity) {\n";
  out << "      count = capacity;\n";
  out << "    }\n";
  out << "    for (uint32_t i = 0; i < count; ++i) {\n";
