  out << "    float* out_dist2,\n";
  out << "    uint32_t capacity,\n";
  out << "    uint32_t* out_count) {\n";
  out << "  return " << prefix << "_infer_ann_query_cached(\n";
  out << "      vector,\n";
  out << "      k,\n";
  out << "      out_centroids,\n";
  out << "      out_dist2,\n";
  out << "      capacity,\n";
  out << "      out_count,\n";
