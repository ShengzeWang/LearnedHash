  out << "    return false;\n";
  out << "  }\n";
  out << "  std::sort(heap.begin(), heap.end(), heap_cmp);\n";
  out << "  out->resize(heap.size());\n";
  out << "  for (std::size_t i = 0; i < heap.size(); ++i) {\n";
